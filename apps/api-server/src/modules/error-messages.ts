const PATTERNS: Array<[RegExp, (match: RegExpMatchArray) => string]> = [
  [/^Order cannot be accepted from status (\w+)$/, () => "订单当前状态不能接单，请刷新"],
  [/^Only ACCEPTED orders can start\. Current status: (\w+)$/, () => "只有已接单的订单可以开始服务"],
  [/^Only unstarted paid orders can be cancelled\. Current status: (\w+)$/, () => "只有未开始服务的订单可以取消"],
  [/^hours cannot be greater than ([\d.]+)$/, m => `时长不能超过 ${m[1]} 小时`],
  [/^(\w+) must be a finite decimal string$/, () => "金额格式不正确"],
  [/^(\w+) must be positive, have at most (\d+) decimal places and not exceed ([\d.]+)$/, m => `金额必须大于 0，最多 ${m[2]} 位小数，且不超过 ${m[3]}`],
  [/^(\w+) must be nonnegative, have at most (\d+) decimal places and not exceed ([\d.]+)$/, m => `金额不能为负数，最多 ${m[2]} 位小数，且不超过 ${m[3]}`],
  [/^Cannot (GET|POST|PATCH|PUT|DELETE) /, () => "请求的地址不存在"],
  [/^requestId is required/, () => "页面已过期，请刷新后重新提交"]
];

const HAS_CJK = /[一-鿿]/;

/** Chinese wording for an API error message, or the message itself when it is already Chinese or unknown. */
export function toChineseError(message: string): string {
  if (!message || HAS_CJK.test(message)) return message;
  const exact = EXACT[message];
  if (exact) return exact;
  for (const [pattern, render] of PATTERNS) {
    const match = message.match(pattern);
    if (match) return render(match);
  }
  return message;
}

/** True when the message has a Chinese wording (already Chinese, or known to the table). */
export function hasChineseError(message: string) {
  return HAS_CJK.test(toChineseError(message));
}
